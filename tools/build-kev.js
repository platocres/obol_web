#!/usr/bin/env node
/*!
 * tools/build-kev.js — compile the CISA KEV pack (data/packs/cisa_kev_*.json) into a compact,
 * browser-bundled lookup (data/kev-catalog.js) so the Frameworks view can flag a detected CVE as
 * "actively exploited in the wild" and whether it is known-ransomware-associated.
 *
 *   node tools/build-kev.js
 *
 * Emits OBOL.KEV = { version, map: { 'CVE-xxxx-n': { rw: 0|1, due: 'YYYY-MM-DD' } } }.
 * Source: CISA Known Exploited Vulnerabilities Catalog (cisa.gov), public domain.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, '..', 'data', 'packs');
const OUT = path.join(__dirname, '..', 'data', 'kev-catalog.js');

function newest(re) {
  return fs.readdirSync(DIR).filter(f => re.test(f)).sort().pop();
}

function main() {
  const file = newest(/^cisa_kev_.*\.json$/);
  if (!file) { console.error('no cisa_kev pack found'); process.exit(1); }
  const pack = JSON.parse(fs.readFileSync(path.join(DIR, file), 'utf8'));
  const cves = pack.cves || [];
  const map = {};
  cves.forEach(c => {
    const id = String(c.cve || '').trim().toUpperCase();
    if (!/^CVE-\d{4}-\d+$/.test(id)) return;
    const rw = (c.ransomware === true || /^(true|known)$/i.test(String(c.ransomware || ''))) ? 1 : 0;
    map[id] = { rw: rw, due: String(c.dueDate || '').trim() };
  });
  const version = pack.catalog_version || pack.snapshot_date || 'cisa-kev';
  const header = '/*!\n'
    + ' * data/kev-catalog.js — compact CISA Known Exploited Vulnerabilities lookup (GENERATED by\n'
    + ' * tools/build-kev.js). Flags a detected CVE as actively exploited. Source: CISA KEV Catalog\n'
    + ' * (cisa.gov), public domain. Catalog ' + version + '.\n'
    + ' */\n';
  const body = '(function (root) {\n  "use strict";\n  var OBOL = root.OBOL = root.OBOL || {};\n'
    + '  OBOL.KEV = { version: ' + JSON.stringify(version) + ', map: ' + JSON.stringify(map) + ' };\n'
    + '  if (typeof module !== "undefined" && module.exports) { module.exports = OBOL.KEV; }\n'
    + '})(typeof globalThis !== "undefined" ? globalThis : this);\n';
  fs.writeFileSync(OUT, header + body);
  console.log('wrote', OUT, '(' + (fs.statSync(OUT).size / 1024).toFixed(0) + ' KB) from', file);
  console.log('KEV entries:', Object.keys(map).length, '| ransomware-flagged:', Object.values(map).filter(v => v.rw).length);
}

main();
