#!/usr/bin/env node
/* Generate data/playbooks-bundle.js — a single committed global (OBOL.playbookData) from the
 * vendored obol-local playbook JSONs, so playbooks load over file:// and http with no fetch
 * and no runtime build. Mirrors tools/build-packs.js. Re-run after editing
 * data/playbooks/*.json:  node tools/build-playbooks.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const PLAYBOOKS_DIR = path.join(__dirname, '..', 'data', 'playbooks');
const OUT = path.join(__dirname, '..', 'data', 'playbooks-bundle.js');

// Load order = obol-local list_playbooks() order: shipped playbooks sorted by name.
const files = fs.readdirSync(PLAYBOOKS_DIR)
  .filter((f) => f.endsWith('.json'))
  .sort();

const data = {};
const names = [];
files.forEach((f) => {
  const p = path.join(PLAYBOOKS_DIR, f);
  let json;
  try {
    json = JSON.parse(fs.readFileSync(p, 'utf8'));
  } catch (e) {
    console.warn('skipping unparseable playbook: ' + f + ' (' + e.message + ')');
    return;
  }
  if (!json || !json.name) { console.warn('skipping playbook without name: ' + f); return; }
  data[json.name] = json;
  names.push(json.name);
});
names.sort(); // by name — matches obol-local sorted(by_name)

let stepCount = 0;
names.forEach((n) => { stepCount += (data[n].steps || []).length; });

const banner = '/*! obol data — playbooks-bundle.js — GENERATED by tools/build-playbooks.js. Do not edit by hand.\n'
  + ' * Source: data/playbooks/*.json (vendored from obol-local). ' + names.length
  + ' playbooks, ' + stepCount + ' steps. */\n';

const body = '(function (root) {\n'
  + '  "use strict";\n'
  + '  var OBOL = root.OBOL = root.OBOL || {};\n'
  + '  OBOL.playbookData = ' + JSON.stringify(data) + ';\n'
  + '  OBOL.PLAYBOOK_NAMES = ' + JSON.stringify(names) + ';\n'
  + '})(typeof globalThis !== "undefined" ? globalThis : this);\n';

fs.writeFileSync(OUT, banner + body);
console.log('Wrote ' + OUT + ' (' + names.length + ' playbooks, ' + stepCount + ' steps, '
  + (fs.statSync(OUT).size / 1024).toFixed(1) + ' KB).');
