'use strict';
// Guards the publish de-provenancing scrub against the class of bug that once shipped broken code to the
// public mirror: the text-level rules must never alter a code token (a variable named like a lineage
// keyword), only comments and non-code files. See tools/publish/publish.mjs.
const path = require('path');
const { pathToFileURL } = require('url');

(async () => {
  const mod = await import(pathToFileURL(path.join(__dirname, '..', '..', 'tools', 'publish', 'publish.mjs')).href);
  const { scrub, FORBIDDEN } = mod;
  let passed = 0;
  function check(name, cond) {
    if (cond) { passed++; return; }
    console.error('FAIL: ' + name);
    process.exitCode = 1;
  }

  // 1) Code is left byte-for-byte: a variable named `derived` (which collides with a scrub keyword) and
  //    its uses survive, including the exact call and comparison that the old whole-file scrub corrupted.
  const codeIn = [
    '(function () {',
    '  // (derived from the donor) build, mirrors the original parity checks',
    '  /* Faithful JS port of the engine. Ported from the donor. */',
    '  var derived = deriveCommand(text);',
    '  if (derived && raw && (extractTool(derived) !== extractTool(raw))) originalAction = "";',
    '  var dispatch = dispatchLabel(derived, text);',
    '  return parse(dispatch || derived);',
    '})();',
    '',
  ].join('\n');
  const outJs = scrub(codeIn, 'assets/ui/x.js');
  check('code: `var derived =` preserved', /var derived = deriveCommand\(text\);/.test(outJs));
  check('code: call argument preserved', /dispatchLabel\(derived, text\)/.test(outJs));
  check('code: comparison preserved', /extractTool\(derived\) !== extractTool\(raw\)/.test(outJs));
  check('code: `|| derived` preserved', /dispatch \|\| derived/.test(outJs));
  check('output still parses', (() => { try { new Function(outJs); return true; } catch (e) { return false; } })());

  // 2) Comments ARE scrubbed: the lineage notes inside comments are removed.
  check('comment: parenthetical note stripped', !/derived from/.test(outJs));
  check('comment: "Faithful JS port of" stripped', !/Faithful JS port of/.test(outJs));
  check('comment: "Ported from" stripped', !/Ported from/.test(outJs));

  // 3) Renames stay global, so a forbidden product name in a code string is still normalized.
  const urlJs = 'var site = "https://platocres.github.io/obol_web/";\n';
  check('rename: obol_web normalized in code string', !/obol_web/.test(scrub(urlJs, 'a.js')));

  // 4) Non-code text scrubs whole (markdown has no "code" to protect).
  check('md: lineage note stripped whole-file', !/derived from/.test(scrub('Built (derived from the donor).\n', 'README.md')));

  // 4b) String literals ARE scrubbed (lineage in a generated-header string, as build-packs.js emits).
  const strOut = scrub("var banner = 'GENERATED by tools/build-packs.js (vendored from obol-local)';\n", 'tools/build.js');
  check('string: "GENERATED by <path>" collapsed', !/GENERATED by tools/.test(strOut));
  check('string: obol-local removed from string', !/obol-local/.test(strOut));

  // 4c) Template literals are left as code (never corrupted): a ${call(keyword)} survives intact.
  const tplOut = scrub('var t = `x ${build(derived)} y`;\n', 'a.js');
  check('template: ${build(derived)} preserved', /build\(derived\)/.test(tplOut));

  // 5) The scrubbed code sample carries no forbidden token.
  FORBIDDEN.forEach(([label, re]) => check('gate: no "' + label + '" survives', !re.test(outJs)));

  if (process.exitCode) console.error('PUBLISH SCRUB SMOKE: failures above');
  else console.log('PUBLISH SCRUB SMOKE: ' + passed + ' checks passed');
})().catch((e) => { console.error(e); process.exit(1); });
