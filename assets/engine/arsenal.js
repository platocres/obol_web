/*!
 * obol engine — arsenal.js
 * Turns OBOL.ARSENAL into the operator's setup artifacts, entirely client-side (no backend):
 *   - buildScript()    -> the text of download-arsenal.sh (fetch + cache + stage, obol-local parity)
 *   - parseInventory() -> (Phase 2) read the OBOL-ARSENAL block the script prints back
 * The browser never fetches or executes anything; it only GENERATES a script the operator runs on
 * their own Kali box. Integrity mirrors obol-local: fetch upstream `latest` unless a version/sha256
 * is pinned, record every file's real sha256 (trust-on-first-use), allowlisted hosts only.
 */
(function (root) {
  'use strict';
  var OBOL = root.OBOL = root.OBOL || {};

  var CACHE = '"$HOME/.obol/arsenal"';   // machine-global cache (not per-engagement), like obol-local's $OBOL_HOME/cache
  var TOOLDIR = '"$HOME/tools"';          // run-from-repo clones land here

  function sh(s) { return String(s == null ? '' : s); }
  // A fetch line for a direct-url material; records sha256 into the cache index.
  function fetchUrl(e) {
    return 'obol_fetch "' + e.key + '" "' + sh(e.url) + '" "' + sh(e.dest || e.key) + '"'
      + (e.sha256 ? ' "' + e.sha256 + '"' : '');
  }
  // A fetch line for a GitHub release-asset material (regex-resolved), optionally extracting a member.
  function fetchGh(e) {
    return 'obol_fetch_gh "' + e.key + '" "' + sh(e.gh_repo) + '" "' + sh(e.gh_asset) + '" "'
      + sh(e.dest || e.key) + '" "' + sh(e.extract_member || '') + '"';
  }

  // The reusable shell preamble: helpers for detect / apt / pipx / git / fetch-with-digest.
  function preamble() {
    return [
      '#!/usr/bin/env bash',
      '# download-arsenal.sh — generated by obol-web (Loadout). Review before running; it only fetches',
      '# published tools to YOUR machine and records each file\'s sha256. Nothing here is obol-specific.',
      '# Re-running is safe: everything is check-then-install, so it only does the missing work.',
      'set -uo pipefail',
      'CACHE=' + CACHE + '; TOOLDIR=' + TOOLDIR + '; WWW="${1:-$CACHE/www}"',
      'mkdir -p "$CACHE" "$CACHE/win" "$CACHE/lin" "$TOOLDIR" "$WWW"',
      'IDX="$CACHE/index.json"; [ -f "$IDX" ] || echo "{}" > "$IDX"',
      // pipx + user-local installs land here; put it on PATH now so the inventory probe sees them this run.
      'export PATH="$HOME/.local/bin:$PATH"',
      'export PIP_BREAK_SYSTEM_PACKAGES=1',   // PEP 668: tolerate pip on externally-managed Kali/Debian
      // optional: a GitHub token lifts the 60/hr anonymous API limit used to resolve release assets.
      'GH_AUTH=(); [ -n "${GITHUB_TOKEN:-}" ] && GH_AUTH=(-H "Authorization: Bearer $GITHUB_TOKEN")',
      'SUDO=""; if [ "$(id -u)" -ne 0 ]; then command -v sudo >/dev/null 2>&1 && SUDO="sudo"; fi',
      'have(){ command -v "$1" >/dev/null 2>&1; }',
      'say(){ printf "  \\033[1;32m•\\033[0m %s\\n" "$1"; }',
      'skip(){ printf "  \\033[2m- %s (present)\\033[0m\\n" "$1"; }',
      'warn(){ printf "  \\033[1;33m! %s\\033[0m\\n" "$1"; }',
      '# record "<key> <sha256> <path>" into a flat sidecar the paste-back block reads.',
      'REC="$CACHE/.records"; : > "$REC"',
      'rec(){ printf "%s %s %s\\n" "$1" "$2" "$3" >> "$REC"; }',
      'obol_apt(){ have "$2" && { skip "$2"; return; }; say "apt $1"; $SUDO apt-get install -y "$1" >/dev/null 2>&1 || warn "apt $1 failed"; }',
      'obol_pipx(){ have "$2" && { skip "$2"; return; }; say "pipx $1"; pipx install "$1" >/dev/null 2>&1 || pipx install --force "$1" >/dev/null 2>&1 || warn "pipx $1 failed (try: pipx install $1)"; }',
      'obol_git(){ local d="$TOOLDIR/$2"; [ -d "$d" ] && { skip "$2"; return; }; say "git $2"; git clone --depth 1 "$1" "$d" >/dev/null 2>&1 || warn "clone $2 failed"; }',
      '# obol_fetch <key> <url> <dest> [sha256]',
      'obol_fetch(){ local k="$1" u="$2" d="$3" pin="${4:-}" out="$CACHE/$3"; ',
      '  [ -s "$out" ] || { say "fetch $k"; curl -fsSL "$u" -o "$out" || { warn "fetch $k failed"; return; }; }; ',
      '  local h; h=$(sha256sum "$out" | cut -d" " -f1); ',
      '  if [ -n "$pin" ] && [ "$h" != "$pin" ]; then warn "$k sha256 MISMATCH (pinned) — deleting"; rm -f "$out"; return; fi; ',
      '  rec "$k" "$h" "$out"; }',
      '# obol_fetch_gh <key> <repo> <asset-regex> <dest> [extract-member-regex]',
      'obol_fetch_gh(){ local k="$1" repo="$2" re="$3" d="$4" mem="${5:-}" out="$CACHE/$4"; ',
      '  [ -s "$out" ] && { local h0; h0=$(sha256sum "$out"|cut -d" " -f1); rec "$k" "$h0" "$out"; skip "$k"; return; }; ',
      '  say "fetch $k ($repo)"; ',
      '  local url; url=$(curl -fsSL "${GH_AUTH[@]}" "https://api.github.com/repos/$repo/releases/latest" | grep -oE "https://[^\\\"]*" | grep -E "$re" | head -n1); ',
      '  [ -n "$url" ] || { warn "$k: no asset matched /$re/"; return; }; ',
      '  local tmp; tmp=$(mktemp); curl -fsSL "$url" -o "$tmp" || { warn "fetch $k failed"; return; }; ',
      '  case "$url" in ',
      '    *.zip) if [ -n "$mem" ]; then (cd "$CACHE" && unzip -o -j "$tmp" >/dev/null 2>&1); local f; f=$(cd "$CACHE" && find . -type f | grep -E "$mem" | head -n1); [ -n "$f" ] && mv "$CACHE/$f" "$out"; else unzip -o -j "$tmp" -d "$CACHE" >/dev/null 2>&1; fi ;; ',
      '    *.tar.gz|*.tgz) tar -xzf "$tmp" -C "$CACHE" >/dev/null 2>&1; if [ -n "$mem" ]; then local f; f=$(cd "$CACHE" && find . -type f | grep -E "$mem" | head -n1); [ -n "$f" ] && mv "$CACHE/$f" "$out"; fi ;; ',
      '    *.gz) gunzip -c "$tmp" > "$out" 2>/dev/null ;; ',
      '    *) mv "$tmp" "$out" ;; ',
      '  esac; rm -f "$tmp"; ',
      '  [ -s "$out" ] || { warn "$k: nothing extracted"; return; }; ',
      '  local h; h=$(sha256sum "$out"|cut -d" " -f1); rec "$k" "$h" "$out"; }',
      ''
    ].join('\n');
  }

  // Build the full script. opts.only (array of classes) narrows what it provisions (e.g. a scope lens).
  function buildScript(opts) {
    opts = opts || {};
    var A = OBOL.ARSENAL || {};
    var keys = Object.keys(A).sort();
    var seen = {};   // de-dupe shared entries (aliases point at one object)
    var apt = [], pipx = [], git = [], lin = [], win = [];
    keys.forEach(function (k) {
      var e = A[k];
      if (!e || seen[e.key]) return; seen[e.key] = 1;
      if (e.class === 'kali' || e.class === 'builtin') return;    // assumed present on Kali
      if (e.class === 'apt') apt.push('obol_apt "' + sh(e.install.replace(/^.*install\s+-y\s+/, '')) + '" "' + (e.bins && e.bins[0] || e.key) + '"');
      else if (e.class === 'pipx') pipx.push('obol_pipx "' + sh((e.install || '').replace(/^pipx install\s+/, '')) + '" "' + (e.bins && e.bins[0] || e.canonical || e.key) + '"');
      else if (e.class === 'git') git.push('obol_git "' + sh((e.install || '').replace(/^git clone\s+/, '').replace(/\s+\S+\/tools\/.*$/, '')) + '" "' + e.key + '"');
      else if (e.class === 'material' || e.class === 'stage-lin') lin.push(e.gh_repo ? fetchGh(e) : fetchUrl(e));
      else if (e.class === 'stage-win') win.push(e.gh_repo ? fetchGh(e) : fetchUrl(e));
    });

    var out = [preamble()];
    out.push('printf "\\n\\033[1mobol arsenal\\033[0m — stocking your box (cache: $CACHE)\\n\\n"');
    // Sudo is used ONLY for apt (base packages + the pipx bootstrap); pipx/git/fetch/stamp all run as you.
    // Prime it once up front so the password is asked now, not mid-download, and keep the ticket warm.
    out.push('if [ -n "$SUDO" ]; then printf "  apt packages need sudo — you may be prompted for your password once.\\n"; $SUDO -v || warn "sudo unavailable — apt + pipx-bootstrap steps will be skipped (install those tools manually)"; ( while true; do $SUDO -n true 2>/dev/null; sleep 50; done ) & SUDO_KEEPALIVE=$!; trap \'kill "$SUDO_KEEPALIVE" 2>/dev/null\' EXIT; fi');
    out.push('');
    // bootstrap: a fresh Kali may lack curl/git/unzip or pipx; take it 0→ready (PEP 668-safe, older-tolerant).
    out.push('echo "[prep] base packages + pipx"');
    out.push('APT_READY=0');
    out.push('ensure_apt(){ [ "$APT_READY" = "1" ] || { $SUDO apt-get update -y >/dev/null 2>&1; APT_READY=1; }; }');
    out.push('for b in curl git unzip tar; do have "$b" || { ensure_apt; say "apt $b"; $SUDO apt-get install -y "$b" >/dev/null 2>&1 || warn "apt $b failed"; }; done');
    out.push('if ! have pipx; then ensure_apt; say "installing pipx";');
    out.push('  $SUDO apt-get install -y pipx >/dev/null 2>&1 || python3 -m pip install --user pipx >/dev/null 2>&1 || warn "pipx bootstrap failed — install it and re-run";');
    out.push('  pipx ensurepath >/dev/null 2>&1 || true; export PATH="$HOME/.local/bin:$PATH";');
    out.push('fi');
    out.push('');
    if (pipx.length) { out.push('echo "[pipx] AD tooling Kali omits"'); out.push.apply(out, pipx); out.push(''); }
    if (apt.length) { out.push('echo "[apt] extra packages"'); out.push.apply(out, apt); out.push(''); }
    if (git.length) { out.push('echo "[git] run-from-repo tools -> $TOOLDIR"'); out.push.apply(out, git); out.push(''); }
    if (lin.length) { out.push('echo "[linux] enum/privesc/pivot staged to $CACHE"'); out.push.apply(out, lin); out.push(''); }
    if (win.length) {
      out.push('echo "[windows] binaries staged to $CACHE/win (copy to your www/ to serve) — Defender will flag these"');
      out.push.apply(out, win);
      out.push('cp -f "$CACHE"/*.exe "$CACHE"/*.bat "$CACHE"/*.ps1 "$WWW"/ 2>/dev/null || true');
      out.push('');
    }
    // shell setup: the obol prompt stamp (UTC time + VPN IP before each prompt). Additive + idempotent —
    // it appends a precmd hook to ~/.zshrc, never replacing your prompt. Powers whole-session import
    // (timeline ordering + auto {{lhost}}). Written to the invoking user's ~/.zshrc, so run this as yourself.
    out.push('echo "[shell] obol prompt stamp (UTC + VPN IP)"');
    out.push('ZRC="$HOME/.zshrc"');
    out.push('if grep -q obol_stamp "$ZRC" 2>/dev/null; then skip "obol prompt stamp"; else');
    out.push('cat >> "$ZRC" <<\'OBOL_ZSH\'');
    out.push('# obol: stamp each prompt with the UTC time + VPN IP (keeps your existing prompt).');
    out.push('obol_stamp() {');
    out.push('  local dev ip');
    out.push('  read -r dev ip <<< "$(ip -4 -o addr show 2>/dev/null | awk \'$2 ~ /^(tun|tap|wg)/ {split($4,a,\"/\"); print $2, a[1]; exit}\')"');
    out.push('  print -P "%F{244}[$(date -u \'+%Y-%m-%d %H:%M:%S UTC\')]${ip:+ [$dev:$ip]}%f"');
    out.push('}');
    out.push('precmd_functions+=(obol_stamp)');
    out.push('OBOL_ZSH');
    out.push('say "added obol prompt stamp to ~/.zshrc — open a new terminal (or: source ~/.zshrc) to see it"; fi');
    out.push('');
    // the paste-back block: a single OBOL-ARSENAL v1 line obol-web ingests to learn this box.
    out.push('# ---- paste the block below back into obol-web (Loadout) ----');
    out.push('emit(){ printf "%s" "$1"; }');
    out.push('INV=$(python3 - "$REC" "$WWW" <<\'PY\'');
    out.push('import json,sys,os,shutil');
    out.push('rec,www=sys.argv[1],sys.argv[2]');
    out.push('tools={}');
    out.push('def which(n):');
    out.push('    return shutil.which(n) or ""');
    out.push('# presence + path + which-variant for every tool name obol asks about:');
    out.push('names=' + JSON.stringify(inventoryNames(A)));
    out.push('for n,variants in names.items():');
    out.push('    hit=""');
    out.push('    for v in variants:');
    out.push('        p=which(v)');
    out.push('        if p: hit=v; tools[n]={"present":True,"invocation":v,"path":p}; break');
    out.push('    if not hit: tools.setdefault(n,{"present":False})');
    out.push('staged=[]');
    out.push('if os.path.isdir(www):');
    out.push('    staged=[f for f in os.listdir(www) if os.path.isfile(os.path.join(www,f))]');
    out.push('digests={}');
    out.push('try:');
    out.push('    for line in open(rec):');
    out.push('        parts=line.split()');
    out.push('        if len(parts)>=2: digests[parts[0]]=parts[1]');
    out.push('except FileNotFoundError: pass');
    out.push('wl={}');
    out.push('for name,path in {"rockyou":"/usr/share/wordlists/rockyou.txt","seclists":"/usr/share/seclists","rockyou-gz":"/usr/share/wordlists/rockyou.txt.gz"}.items():');
    out.push('    if os.path.exists(path): wl[name]=path');
    out.push('print(json.dumps({"v":1,"tools":tools,"staged":staged,"wwwdir":www,"digests":digests,"wordlists":wl}))');
    out.push('PY');
    out.push(')');
    out.push('printf "\\n\\033[1;36mOBOL-ARSENAL v1\\033[0m\\n%s\\n" "$INV"');
    out.push('printf "\\n\\033[1mDone.\\033[0m Copy the OBOL-ARSENAL line above into obol-web → Loadout.\\n"');
    out.push('have pipx && printf "\\033[2m(new pipx tools are on ~/.local/bin — open a new terminal if a command is not found.)\\033[0m\\n" || true');
    return out.join('\n') + '\n';
  }

  // The name->variants map the paste-back probe uses to detect which invocation a box exposes.
  function inventoryNames(A) {
    var names = {}, seen = {};
    Object.keys(A).forEach(function (k) {
      var e = A[k]; if (!e || e.class === 'builtin' || seen[e.key]) return; seen[e.key] = 1;
      names[e.key] = (e.variants && e.variants.length ? e.variants : [e.canonical || e.key]);
    });
    return names;
  }

  // ── paste-back: read the OBOL-ARSENAL block the script prints, into a machine profile ──
  // The profile describes the OPERATOR'S BOX, not an engagement, so it lives per-browser (localStorage),
  // persisting across engagements. Reads are wrapped (a private window / blocked storage just means
  // "no profile yet"). parseInventory tolerates the whole terminal paste — it finds the marker + JSON.
  var PROFILE_KEY = 'obol.arsenal-profile';
  function parseInventory(text) {
    if (!text) return null;
    text = String(text);
    var i = text.indexOf('OBOL-ARSENAL');
    var scan = i >= 0 ? text.slice(i) : text;         // allow a bare JSON paste too
    // find the first balanced {...} after the marker
    var start = scan.indexOf('{');
    if (start < 0) return null;
    var depth = 0, inStr = false, esc = false, end = -1;
    for (var p = start; p < scan.length; p++) {
      var c = scan[p];
      if (inStr) { if (esc) esc = false; else if (c === '\\') esc = true; else if (c === '"') inStr = false; continue; }
      if (c === '"') inStr = true;
      else if (c === '{') depth++;
      else if (c === '}') { depth--; if (depth === 0) { end = p + 1; break; } }
    }
    if (end < 0) return null;
    var obj;
    try { obj = JSON.parse(scan.slice(start, end)); } catch (e) { return null; }
    if (!obj || typeof obj !== 'object' || !obj.tools) return null;
    return obj;
  }
  function profileGet() { try { return JSON.parse(localStorage.getItem(PROFILE_KEY) || 'null'); } catch (e) { return null; } }
  function profileSet(inv) {
    if (!inv) return null;
    inv.savedAt = Date.now();
    try { localStorage.setItem(PROFILE_KEY, JSON.stringify(inv)); } catch (e) {}
    return inv;
  }
  function profileClear() { try { localStorage.removeItem(PROFILE_KEY); } catch (e) {} }
  // Ingest a raw paste → store it as the profile. Returns {ok, present, staged, reason}.
  function ingestInventory(text) {
    var inv = parseInventory(text);
    if (!inv) return { ok: false, reason: 'no OBOL-ARSENAL block found in that paste' };
    profileSet(inv);
    var present = 0; Object.keys(inv.tools || {}).forEach(function (k) { if (inv.tools[k] && inv.tools[k].present) present++; });
    return { ok: true, present: present, staged: (inv.staged || []).length, wordlists: Object.keys(inv.wordlists || {}).length };
  }

  OBOL.arsenal = {
    buildScript: buildScript, inventoryNames: inventoryNames,
    parseInventory: parseInventory, ingestInventory: ingestInventory,
    profileGet: profileGet, profileSet: profileSet, profileClear: profileClear,
  };
})(typeof globalThis !== 'undefined' ? globalThis : this);
